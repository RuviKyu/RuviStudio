/* ============================================================================
   packet.js — the ready-to-send Claude packet (Premiere suite port), FLAT form: two files written
   directly into <title>\Script\ beside the script + word SRT that are
   already there — no subfolder, no duplicated media.
     00_README_FOR_CLAUDE.md      (the briefing: channel, paths, deliverables)
     Channel_Prompt_Suffixes.txt  (copied from <base>\_RUVI PROJECT FILES)
   The user drags FOUR files from Script\ into a project chat: the README,
   the suffixes, the docx, the word-level SRT. Self-healing: rebuilt whenever
   inputs are newer or pieces are missing; legacy packet folders/zips from
   earlier versions are deleted on sight.
   ========================================================================== */
"use strict";
var fs = require("fs");
var path = require("path");

function findFirst(dir, re) {
    var names = [];
    try { names = fs.readdirSync(dir); } catch (e) { return null; }
    for (var i = 0; i < names.length; i++) if (re.test(names[i])) return names[i];
    return null;
}


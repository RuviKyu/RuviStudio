/* ensure(opts) → {ok, built, packet, files, skip}
   opts: { titleFolder, channel, baseDir, version?, force? }
   packet = the Script\ dir itself; files = the four chat-upload names */
function ensure(opts) {
    var tDir = opts.titleFolder;
    var scriptDir = path.join(tDir, "Script");
    var folderName = path.basename(tDir);
    var stem = folderName.replace(/^\d+\.\s*/, "").replace(/[^\w]+/g, "_").replace(/^_+|_+$/g, "");
    var rmPath = path.join(scriptDir, "00_README_FOR_CLAUDE.md");
    var sufDst = path.join(scriptDir, "Channel_Prompt_Suffixes.txt");
    // legacy cleanup: the old zip / folder forms duplicate media — remove on sight
    var cleaned = [];
    try {
        fs.readdirSync(scriptDir).forEach(function (n) {
            if (/_claude_packet(\.zip)?$/i.test(n)) {
                try { fs.rmSync(path.join(scriptDir, n), { recursive: true, force: true }); cleaned.push(n); } catch (e0) {}
            }
        });
    } catch (e00) {}
    var docx = findFirst(scriptDir, /\.(docx?|rtf)$/i);
    var srt = findFirst(scriptDir, /_word_level\.srt$/i) || findFirst(tDir, /_word_level\.srt$/i);
    if (!docx && !srt) return { ok: false, skip: "no script/SRT yet — packet waits for the Grab", cleaned: cleaned };
    var sufSrc = path.join(opts.baseDir, "_RUVI PROJECT FILES", "Channel_Prompt_Suffixes.txt");
    var haveSufSrc = fs.existsSync(sufSrc);
    if (!opts.force && fs.existsSync(rmPath)) {
        try {
            var zt = fs.statSync(rmPath).mtimeMs, newest = 0, missing = false;
            if (docx) newest = Math.max(newest, fs.statSync(path.join(scriptDir, docx)).mtimeMs);
            if (srt) {
                var srtP0 = fs.existsSync(path.join(scriptDir, srt)) ? path.join(scriptDir, srt) : path.join(tDir, srt);
                newest = Math.max(newest, fs.statSync(srtP0).mtimeMs);
            }
            if (haveSufSrc) {
                newest = Math.max(newest, fs.statSync(sufSrc).mtimeMs);
                if (!fs.existsSync(sufDst)) missing = true;
            }
            if (!missing && !cleaned.length && zt >= newest)
                return { ok: true, built: false, packet: scriptDir,
                         files: ["00_README_FOR_CLAUDE.md", "Channel_Prompt_Suffixes.txt", docx, srt].filter(Boolean) };
        } catch (e) {}
    }
    try { fs.mkdirSync(scriptDir, { recursive: true }); } catch (e1) {}
    var haveSuffix = false;
    if (haveSufSrc) { try { fs.copyFileSync(sufSrc, sufDst); haveSuffix = true; } catch (e2) {} }
    fs.writeFileSync(rmPath, readmeText({ channel: opts.channel, folderName: folderName, titleFolder: tDir,
                                          docx: docx, srt: srt, suffixFile: haveSuffix, stem: stem, version: opts.version }));
    return { ok: true, built: true, packet: scriptDir, cleaned: cleaned,
             files: ["00_README_FOR_CLAUDE.md", haveSuffix ? "Channel_Prompt_Suffixes.txt" : null, docx, srt].filter(Boolean) };
}

module.exports = { ensure: ensure, readmeText: readmeText };
